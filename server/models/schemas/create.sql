ADD FOREIGN KEY("id_nota_operatoria") REFERENCES "Nota_Operatoria"("id")
ON UPDATE NO ACTION ON DELETE NO ACTION;

ALTER TABLE "Equipo_Quirurgico"
ADD FOREIGN KEY("id_medico") REFERENCES "Usuarios"("id")
ON UPDATE NO ACTION ON DELETE NO ACTION;

