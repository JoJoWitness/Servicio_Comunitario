CREATE TABLE IF NOT EXISTS "Paciente" (
	"id" UUID NOT NULL UNIQUE,
	"historia_medica" VARCHAR(255) NOT NULL UNIQUE,
	"numero_identifiacion" VARCHAR(255) NOT NULL UNIQUE,
	"tipo_documento" CHAR(1) NOT NULL,
	"nombre" VARCHAR(255) NOT NULL,
	"genero" CHAR(1) NOT NULL,
	"fecha_nacimiento" DATE NOT NULL,
	"numero_telefono" VARCHAR(255) NOT NULL,
	"direccion" VARCHAR(255) NOT NULL,
	"eliminado" BOOLEAN NOT NULL DEFAULT FALSE,
	PRIMARY KEY("id")
);

CREATE TABLE IF NOT EXISTS "Usuarios" (
	"id" UUID NOT NULL UNIQUE,
	"correo" VARCHAR(255) NOT NULL,
	"nombres" VARCHAR(255) NOT NULL,
	"apellidos" VARCHAR(255),
	"contrasena" VARCHAR(255) NOT NULL,
	"rol" VARCHAR(255) NOT NULL,
	"eliminado" BOOLEAN NOT NULL DEFAULT FALSE,
	PRIMARY KEY("id")
);




CREATE TABLE IF NOT EXISTS "Nota_Operatoria" (
	"id" INTEGER NOT NULL UNIQUE GENERATED BY DEFAULT AS IDENTITY,
	"dx_pre_operatorio" TEXT NOT NULL,
	"dx_post_operatorio" TEXT NOT NULL,
	"intervencion_realizada" TEXT NOT NULL,
	"fecha_comienzo" DATE NOT NULL,
	"fecha_culminacion" DATE NOT NULL,
	"hora_comienzo" TIME NOT NULL,
	"hora_culminacion" TIME NOT NULL,
	"resumen_intevencion" TEXT NOT NULL,
	"pabellon" VARCHAR(255) NOT NULL,
	"es_electiva" BOOLEAN NOT NULL,
	"es_emergencia" BOOLEAN NOT NULL,
	"tuvo_biopsia" BOOLEAN NOT NULL,
	"anestesia" VARCHAR(255) NOT NULL,
	"id_paciente" UUID NOT NULL,
	"id_medico_encargado" UUID NOT NULL,
	"eliminado" BOOLEAN NOT NULL DEFAULT FALSE,
    "tipo_lente" VARCHAR(255),
	"created_at" TIMESTAMPTZ NOT NULL DEFAULT NOW(),
	PRIMARY KEY("id")
);




CREATE TABLE IF NOT EXISTS "Equipo_Quirurgico" (
	"id" INTEGER NOT NULL UNIQUE GENERATED BY DEFAULT AS IDENTITY,
	"id_nota_operatoria" INTEGER NOT NULL,
	"id_medico" UUID NOT NULL,
	"rol" VARCHAR(255) NOT NULL DEFAULT 'cirujano',
	PRIMARY KEY("id")
);




CREATE TABLE IF NOT EXISTS "Procedimientos" (
	"id" INTEGER NOT NULL UNIQUE GENERATED BY DEFAULT AS IDENTITY,
	"intervencion" VARCHAR(255) NOT NULL,
	"resumen" TEXT NOT NULL,
	"eliminado" BOOLEAN NOT NULL DEFAULT FALSE,
	PRIMARY KEY("id")
);




CREATE TABLE IF NOT EXISTS "Diagnosticos" (
	"id" INTEGER NOT NULL UNIQUE GENERATED BY DEFAULT AS IDENTITY,
	"procedimientos" VARCHAR(255) NOT NULL,
	"resumen" TEXT NOT NULL,
	"eliminado" BOOLEAN NOT NULL DEFAULT FALSE,
	PRIMARY KEY("id")
);




CREATE TABLE IF NOT EXISTS "Intervencion" (
	"id" INTEGER NOT NULL UNIQUE GENERATED BY DEFAULT AS IDENTITY,
	"tecnica" VARCHAR(255) NOT NULL,
	"eliminado" BOOLEAN NOT NULL DEFAULT FALSE,
	PRIMARY KEY("id")
);



