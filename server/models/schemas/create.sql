ADD FOREIGN KEY("id_procedimiento") REFERENCES "Procedimientos"("id")
ON UPDATE NO ACTION ON DELETE CASCADE;

ALTER TABLE "Procedimiento_Tecnica"
ADD FOREIGN KEY("id_tecnica") REFERENCES "Intervencion"("id")
ON UPDATE NO ACTION ON DELETE CASCADE;
